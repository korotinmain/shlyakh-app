Generated by `tool/sky/build_route.dart`; do not edit by hand
(docs/decisions/0009-sky-data.md).

- Repository: https://github.com/$_repo at commit `$_sha`
${[for (final f in _files) '- https://raw.githubusercontent.com/$_repo/$_sha/$f'].join('\n')}
- Licence: BSD-3-Clause, © Olaf Frohn (d3-celestial).
- Constellation figures: IAU and Sky & Telescope (CC BY 4.0), with line
  modifications by the d3-celestial author.
- Star positions and magnitudes: XHIP (Anderson & Francis 2012), via
  d3-celestial. Positions are J2000 right ascension and declination in
  degrees.
''';
